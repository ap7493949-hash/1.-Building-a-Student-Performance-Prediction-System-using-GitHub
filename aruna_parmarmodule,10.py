import ipywidgets as widgets
from IPython.display import display, clear_output


output = widgets.Output()
filter_button = widgets.Dropdown(
    options=['All Students', 'Pass Only', 'Fail Only'],
    value='All Students',
    description=' Filter:',
    disabled=False,
)


def on_change(change):
    with output:
        clear_output(wait=True)

        if change['new'] == 'Pass Only':
            display(student_table[student_table['Status'] == 'Pass'])
        elif change['new'] == 'Fail Only':
            display(student_table[student_table['Status'] == 'Fail'])
        else:
            display(student_table)


filter_button.observe(on_change, names='value')
print(" Filter the list using the dropdown button below:")
display(filter_button)
